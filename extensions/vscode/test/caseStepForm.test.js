"use strict";

const assert = require("node:assert/strict");
const test = require("node:test");
const loadWebview = require("../test-support/loadWebview");
const {caseDefinitions} = require("../src/caseAuthoring");
const {createBdd} = require("../src/caseBdd");
const executionSection=open=>({isConnected:true,classList:{contains:cls=>cls==="case-step-execution"},open});

test("step details keep a generated summary editable without pinning it or fetching controls until requested",async t=>{
    const view = await loadWebview("caseAuthoring");
    const focused = [];
    const previousDocument = global.document;
    global.document={getElementById:id=>({focus:()=>focused.push(id),select(){}})};
    t.after(()=>{global.document=previousDocument;});
    const step={command:"press",input:{target:{text:"Submit"}}};
    const plan={version:"1",steps:[step]};
    const presentation=new Map([[step,{name:"提交订单",group:"结账"}]]);
    const definitions=caseDefinitions(plan,presentation);
    const bdd=createBdd(plan,"zh",undefined,presentation);
    const review={id:"case",name:"订单",revision:0,edit:true,bdd,definitions,targets:{}};
    const model={caseReview:review,devices:[]};
    const messages=[];
    const send=message=>messages.push(message);
    const render=()=>view.caseReviewView(model,"zh-CN");
    const click=dataset=>view.caseEditorClick({dataset},model,send,render);
    const input=(key,value)=>view.caseEditorInput({dataset:{bddField:key},type:"text",value},model,send,render);
    const submit=()=>view.caseEditorSubmit({target:{hasAttribute:()=>true},preventDefault(){}},model,send);

    click({bdd:"edit",area:"stepDetails",path:"steps[0]",stepDefault:bdd.steps[0].text});
    assert.deepEqual(messages,[]);
    assert.equal(focused[0],"bdd-name");
    assert.match(render(),/id="bdd-description"[^>]*>点击 Submit<\/textarea>/);
    assert.match(render(),/name="bdd-role"/);
    assert.match(render(),/<label>分组<input id="bdd-group"[^>]*value="结账"/);
    assert.match(render(),/<details class="case-step-execution"><summary id="bdd-execution-toggle"/);
    assert.doesNotMatch(render(),/id="bdd-command"/);
    assert.equal((render().match(/id="bdd-editor"/g)||[]).length,1);
    input("name","确认订单");
    input("group","付款");
    submit();
    assert.equal(messages.at(-1).name,"确认订单");
    assert.equal(messages.at(-1).group,"付款");
    assert.equal(Object.hasOwn(messages.at(-1),"descriptionText"),false);
    assert.equal(Object.hasOwn(messages.at(-1),"operationArea"),false);
    input("descriptionText","先核对订单号\n再提交");
    const toggle=open=>view.caseEditorToggle(executionSection(open),model,send,render);
    toggle(true);
    assert.equal(messages.at(-1).type,"caseTargets");
    assert.equal(messages.at(-1).area,"stepOperation");
    assert.match(render(),/id="bdd-command"/);
    assert.match(render(),/<details class="case-step-execution" open>/);
    assert.doesNotMatch(render(),/bdd-action-timing/);
    toggle(true); // A newly rendered open details also emits a native toggle.
    assert.equal(messages.filter(message=>message.type==="caseTargets").length,1);
    input("timeout","5000");
    toggle(false);
    assert.match(render(),/<details class="case-step-execution">/);
    assert.match(render(),/id="bdd-timeout"[^>]*value="5000"/);
    submit();
    assert.equal(messages.at(-1).operationArea,"stepOperation");
    assert.equal(messages.at(-1).timeout,"5000");
    assert.equal(messages.at(-1).descriptionText,"先核对订单号\n再提交");
    input("descriptionText","");
    submit();
    assert.equal(messages.at(-1).descriptionText,"");
});

test("boundary checks and existing generated descriptions share the inline editor at their own position",async t=>{
    const view=await loadWebview("caseAuthoring");
    const previous=global.document;
    global.document={getElementById:()=>({focus(){},select(){}})};
    t.after(()=>{global.document=previous;});
    const start={selector:{text:"欢迎"},property:"visible",equals:true};
    const wrapper={description:{id:"profile",text:"进入个人资料",steps:[{command:"back"}]}};
    const plan={version:"1",preconditions:[start],steps:[wrapper],goals:[{...start}]};
    const presentation=new Map([[start,{name:"已登录"}]]);
    const definitions=caseDefinitions(plan,presentation);
    const bdd=createBdd(plan,"zh",undefined,presentation);
    const review={id:"wrapped",name:"编辑",revision:0,bdd,definitions,targets:{}};
    const model={caseReview:review,devices:[]};
    const messages=[];
    const send=m=>messages.push(m);
    const render=()=>view.caseReviewView(model,"zh");
    const edit=(path,stepDefault)=>view.caseEditorClick({dataset:{bdd:"edit",area:"stepDetails",path,stepDefault}},model,send,render);
    edit("preconditions[0]","欢迎 可见");
    assert.equal((render().match(/id="bdd-editor"/g)||[]).length,1);
    assert.match(render(),/id="bdd-name"[^>]*value="已登录"/);
    view.caseEditorToggle(executionSection(true),model,send,render);
    assert.equal(messages.at(-1).area,"stepCheck");
    assert.equal(messages.at(-1).path,"preconditions[0]");
    assert.match(render(),/id="bdd-pick-screen"/);
    assert.match(render(),/id="bdd-scan"/);
    assert.match(render(),/id="bdd-locator-field"/);
    assert.match(render(),/data-bdd-field="property"/);
    edit("steps[0]",wrapper.description.text);
    assert.equal((render().match(/id="bdd-editor"/g)||[]).length,1);
    assert.match(render(),/<textarea id="bdd-description"[^>]*required[^>]*>进入个人资料/);
    assert.doesNotMatch(render(),/id="bdd-execution-toggle"/);
});
